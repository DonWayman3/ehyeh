  function boot() {
    injectStyles();
    ensureBlock();
    applyMarks();
    var pending = false;
    var obs = new MutationObserver(function () {
      if (pending) { return; }
      pending = true;
      setTimeout(function () {
        pending = false;
        try { ensureBlock(); applyMarks(); } catch (e) {}
      }, 60);
    });
    obs.observe(document.body, { childList: true, subtree: true });
  }
