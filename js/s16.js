    jump.addEventListener('click', function () { gotoPassage(p.b, p.c, p.v); });
    row.appendChild(jump);
    var x = el('button', { 'class': 'hg2c-x', 'aria-label': 'Remove' }, '×');
    x.addEventListener('click', function () {
      var m = loadMarks();
      if (kind === 'bookmark') { delete m.bookmarks[k]; }
      if (kind === 'highlight') { delete m.highlights[k]; }
      if (kind === 'note') { delete m.notes[k]; }
      saveMarks(m); applyMarks(); renderBlock();
    });
