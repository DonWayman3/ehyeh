  function jumpToRef(ref) {
    var m = /^([1-3]?\s?[A-Za-z]+)\.?\s+(\d+)(?::(\d+))?/.exec(String(ref || ''));
    if (!m) { return; }
    var token = m[1].toLowerCase().replace(/\s+/g, ' ').trim();
    var names = bookNames();
    var idx = ABBREV[token.replace(/\s/g, '')] || ABBREV[token] || 0;
    if (!idx) {
      for (var i = 0; i < names.length; i++) {
        var nm = names[i].toLowerCase();
        if (nm === token || nm.indexOf(token) === 0) { idx = i + 1; break; }
      }
    }
    if (!idx) { return; }
    gotoPassage(idx, parseInt(m[2], 10), m[3] ? parseInt(m[3], 10) : null);
  }

