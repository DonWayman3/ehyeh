  function $(s, r) { return (r || document).querySelector(s); }
  function $$(s, r) { return Array.prototype.slice.call((r || document).querySelectorAll(s)); }
  function el(tag, attrs) {
    var n = document.createElement(tag);
    if (attrs) { Object.keys(attrs).forEach(function (k) {
      if (k === 'class') { n.className = attrs[k]; }
      else if (k.slice(0, 2) === 'on') { n.addEventListener(k.slice(2), attrs[k]); }
      else { n.setAttribute(k, attrs[k]); }
    }); }
    for (var i = 2; i < arguments.length; i++) {
      var kid = arguments[i];
      if (kid == null) { continue; }
      n.appendChild(typeof kid === 'string' ? document.createTextNode(kid) : kid);
    }
    return n;
  }
  function clear(node) { while (node && node.firstChild) { node.removeChild(node.firstChild); } }
  function escT(s) { return String(s == null ? '' : s); }

  /* ---------------- shared book metadata ---------------- */
  function bookNames() {
    try { if (window.SSB && SSB.db()) { return SSB.db().books; } } catch (e) {}
    return (window.HAGAH_PD_TEXTS && HAGAH_PD_TEXTS.books) || [];
  }
  function chapterCount(b) {
    try { if (window.SSB && SSB.db()) { return SSB.db().chapter_counts[String(b)] || 0; } } catch (e) {}
    return (window.HAGAH_PD_TEXTS && HAGAH_PD_TEXTS.chapter_counts[b - 1]) || 0;
  }
  function refLabel(b, c, v) {
    var names = bookNames();
    return (names[b - 1] || ('Book ' + b)) + ' ' + c + (v ? ':' + v : '');
  }

  /* ---------------- passage jumping through the app's own UI ------------ */
  function gotoPassage(b, c, v) {
    try {
      var modeBtn = document.querySelector('[data-hg-mode="study"]');
      if (modeBtn) { modeBtn.click(); }
      /* Surface the reader the way the shell's own Bible door does, then
         select its tab. The reader engine boots lazily on first open —
         drive the selects only once they have options, retrying briefly. */
      var door = $$('button.hg6-door').filter(function (d) { return d.textContent.trim() === 'Bible'; })[0];
      if (door) { door.click(); }
      var tab = document.querySelector('[data-hg-tab="scripture"]');
      if (tab) { tab.click(); }
      var sub = document.querySelector('[data-hg-subview="study"]');
      if (sub) { sub.click(); }
      var tries = 0;
      (function drive() {
        tries++;
        var selB = $('#st-book'), selC = $('#st-chapter');
        if (selB && selC && selB.options.length) {
          selB.value = String(b);
          selB.dispatchEvent(new Event('change', { bubbles: true }));
          selC.value = String(c);
          selC.dispatchEvent(new Event('change', { bubbles: true }));
          if (v) {
            setTimeout(function () {
              var p = document.querySelector('#st-text p.verse[data-verse="' + v + '"]');
              if (p) {
                p.scrollIntoView({ block: 'center' });
                p.classList.add('hg2c-flash');
                setTimeout(function () { p.classList.remove('hg2c-flash'); }, 2200);
              }
            }, 450);
          }
          return;
        }
        if (tries < 12) { setTimeout(drive, 250); }
      })();
    } catch (e) { /* jumping is best-effort; the app itself is never broken by this layer */ }
  }

