
/* ==========================================================================
   Hagah W2-C layer — GO-LIVE Wave 2, lane W2-C (BUILD_QUEUE #236)
   Three staged builds, in the established Hagah layer pattern: this script
   drives the app only through its own UI and DOM observation. It modifies
   no engine internals, makes no network calls, and writes nothing outside
   localStorage key 'hagah.marks.v1' (F-3, this device only).

   F-2  Public-domain translation shelf (WEB · ASV · YLT · Darby) — texts in
        HAGAH_PD_TEXTS (generated by tools/build_pd_texts.py, validated
        against the in-app canon). Geneva (1599) + KJV remain in the main
        reader; the shelf is where the four added public-domain texts live.
   F-6  Word Studies shelf — renders HAGAH_WS_SIDECAR (the generated display
        sidecar) inside Study Helps. Only CHECKED / TEACHING-READY entries
        render; the client re-filters as defense in depth. Teaching notes
        part (a) only — (b)/(c) and the psyop sidebar never render, exactly
        as the staged preview (spec: HAGAH_WORD_STUDIES_SPEC.md).
   F-3  Notes / highlights / bookmarks — local-first on this device, with a
        backup file export + import. No accounts, no sync (by design).
   ========================================================================== */
